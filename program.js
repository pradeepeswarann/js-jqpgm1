

// JavaScript program to calculate the area of a rectangle

// Store the length and breadth of the rectangle
let length = 10;
let breadth = 5;

// Calculate the area using the formula:
// Area = Length × Breadth
let area = length * breadth;

// Display the result
console.log("Length:", length);
console.log("Breadth:", breadth);
console.log("Area of Rectangle:", area);
